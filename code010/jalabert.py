# ------------------------------------------------------------------ 2. Eisenstein ideals
def hnf(v1, v2):
    a, b = v1; c, d = v2
    while c != 0:
        q = a//c; a, b, c, d = c, d, a - q*c, b - q*d
    if a < 0: a, b = -a, -b
    if d < 0: d = -d
    return (a, b % d if d else b, d)

def ideal(k, h):
    """the ideal generated by k + h*zeta, as a lattice in the coordinates (k, h); zeta*(k,h) = (-h, k+h)"""
    return hnf((k, h), (-h, k + h))

def phase_group(al, be, L):
    """K_Q for alpha = e(al/L), beta = e(be/L): generated by (beta alpha^-2, (alpha beta)^-1), ((alpha beta)^-1, alpha beta^-2)"""
    g1 = ((be - 2*al) % L, (-al - be) % L); g2 = ((-al - be) % L, (al - 2*be) % L)
    K = {(0, 0)}; todo = [(0, 0)]
    while todo:
        x = todo.pop()
        for g in (g1, g2):
            y = ((x[0] + g[0]) % L, (x[1] + g[1]) % L)
            if y not in K: K.add(y); todo.append(y)
    return K

def annihilator(K, L):
    """lattice of the (k, h) with Z_2^k Z_1^h = 1 on K, that is, of the elements k t_11 + h t_12 of N_Q"""
    vecs = [(k, h) for k in range(L) for h in range(L) if all((h*z1 + k*z2) % L == 0 for z1, z2 in K)]
    lat = None; basis = [(L, 0), (0, L)] + vecs
    cur = hnf(basis[0], basis[1])
    for v in basis[2:]:
        a, b, d = cur
        # lattice spanned by (a,b), (0,d), v : reduce by repeated hnf
        r1 = hnf((a, b), v); a1, b1, d1 = r1
        cur = (a1, b1 % gcd(d1, d) if gcd(d1, d) else b1, gcd(d1, d))
    return cur

def law_of_ideal(k, h):
    """multiset of the numbers |1 + Z_1 + Z_2|^2 over the dual of Z[omega]/(k + h zeta)"""
    a, b, d = ideal(k, h); n = a*d            # lattice basis (a, b), (0, d) in coordinates (k, h)
    vals = []
    # characters: (s, t) with chi(k,h) = e(s k + t h), trivial on the lattice: a s + b t in Z, d t in Z
    for j in range(d):
        t = Fr(j, d)
        for i in range(a):
            s = (Fr(i) - b*t)/a
            z2, z1 = 2*pi*float(s), 2*pi*float(t)       # Z_2 = chi(t_11), Z_1 = chi(t_12)
            vals.append(round(3 + 2*cos(z1) + 2*cos(z2) + 2*cos(z1 - z2), 8))
    assert len(vals) == n
    return tuple(sorted(vals))

def part2():
    ok = True
    # (a) the recipe of Theorem 5.10
    count = 0
    for k in range(-8, 9):
        for h in range(-8, 9):
            n = k*k + k*h + h*h
            if not 0 < n <= 60: continue
            L = 3*n; al = (-(h + 2*k)) % L; be = (h - k) % L     # alpha = p^2, beta = q^2
            K = phase_group(al, be, L)
            good = (len(K) == n) and (annihilator(K, L) == ideal(k, h)); ok &= good; count += 1
            if not good: out('   FAILURE at', (k, h))
    out('Theorem 5.10, recipe: %d elements k + h*zeta of norm <= 60 tested:' % count, ok)
    # (b) all root-of-unity rows give ideals
    seen = set(); stable = True
    for L in range(1, 37):
        for a in range(L):
            for b in range(L):
                K = phase_group(2*a % L, 2*b % L, L)
                k0, b0, d0 = annihilator(K, L)
                for v in ((k0, b0), (0, d0)):
                    w = (-v[1], v[0] + v[1])                    # multiplication by zeta
                    # w must belong to the lattice (k0, b0), (0, d0)
                    stable &= (w[0] % k0 == 0) and ((w[1] - (w[0]//k0)*b0) % d0 == 0)
                seen.add(len(K))
    ok &= stable
    loeschian = sorted({k*k + k*h + h*h for k in range(8) for h in range(8)} - {0})
    out('all rows (1, p, q) with p, q roots of unity of order <= 36 give ideals:', stable)
    out('   orders of K_Q found, up to 40:', sorted(x for x in seen if x <= 40))
    out('   norms of Eisenstein integers, up to 40:', [x for x in loeschian if x <= 40])
    ok &= set(x for x in seen if x <= 40) <= set(loeschian)
    # (c) the law separates ideals up to conjugation
    ideals = {}
    R = 24
    for k in range(-R, R+1):
        for h in range(-R, R+1):
            n = k*k + k*h + h*h
            if 0 < n <= 400: ideals.setdefault(ideal(k, h), (k, h))
    bynorm = defaultdict(list)
    for I, (k, h) in ideals.items(): bynorm[k*k + k*h + h*h].append((I, (k, h)))
    bad = 0; classes = 0
    for n, lst in bynorm.items():
        laws = defaultdict(set)
        for I, (k, h) in lst: laws[law_of_ideal(k, h)].add(I)
        for lw, grp in laws.items():
            classes += 1
            I0 = next(iter(grp)); k, h = ideals[I0]
            conj = ideal(h, k)                                   # conjugation exchanges k and h, up to a unit
            if not grp <= {I0, conj}: bad += 1
    ok &= (bad == 0)
    out('%d ideals of norm <= 400, %d different laws, coincidences other than conjugation: %d' % (len(ideals), classes, bad))
    # (d) the examples of the paper
    for name, al, be, L in (('K_33   p=1, q=e(1/3)', 0, 2, 3), ('cube   p=1, q=i', 0, 2, 4), ('Fano   p=e(1/7), q=e(3/7)', 2, 6, 7),
                            ('Nauru  p=1, q=e(1/12)', 0, 2, 12)):
        K = phase_group(al, be, L); a, b, d = annihilator(K, L)
        out('   %-28s |K_Q| = %2d, annihilator lattice (%d,%d),(0,%d)' % (name, len(K), a, b, d))
    return ok

# ------------------------------------------------------------------ 3. coset graphs
def part3():
    try:
        import networkx as nx
    except Exception:
        out('networkx missing: identification of the coset graphs skipped'); return True
    def torus(k, h):
        a, b, d = ideal(k, h)
        def red(u):
            x, y = u; q = x//a; return (x - q*a, (y - q*b) % d)
        G = nx.Graph()
        for x in range(a):
            for y in range(d):
                for t in ((0, 0), (1, 0), (0, 1)):          # left vertex u joined to u, u + t_11, u + t_12
                    G.add_edge(('L', (x, y)), ('R', red((x + t[0], y + t[1]))))
        return G
    def gp(n, k):
        G = nx.Graph()
        for i in range(n):
            G.add_edge(('o', i), ('o', (i+1) % n)); G.add_edge(('o', i), ('i', i)); G.add_edge(('i', i), ('i', (i+k) % n))
        return G
    named = {(1, 1): ('K_33', nx.complete_bipartite_graph(3, 3)), (2, 0): ('cube', nx.hypercube_graph(3)),
             (2, 1): ('Heawood', nx.heawood_graph()), (3, 0): ('Pappus', nx.pappus_graph()), (2, 2): ('Nauru = GP(12,5)', gp(12, 5))}
    ok = True
    for (b, c), (name, H) in named.items():
        G = torus(b, c); good = nx.is_isomorphic(G, H); ok &= good
        out('   {6,3}_(%d,%d): %2d vertices, girth %d, isomorphic to %s: %s' % (b, c, G.number_of_nodes(), nx.girth(G), name, good))
    for (b, c) in ((3, 1), (4, 0), (3, 2), (4, 1)):
        G = torus(b, c)
        out('   {6,3}_(%d,%d): %2d vertices, girth %d, cubic: %s' % (b, c, G.number_of_nodes(), nx.girth(G), all(dg == 3 for _, dg in G.degree())))
    return ok

