# ------------------------------------------------------------------ 1. generic laws, lattices
def W(N, j, memo={}):
    """E|s|^(2j) for the N-step planar walk: sum of squared multinomial coefficients."""
    if (N, j) in memo: return memo[(N, j)]
    r = 1 if N == 1 else sum(comb(j, a)**2*W(N-1, j-a) for a in range(j+1))
    memo[(N, j)] = r; return r

def c_generic_two_rows(N, n):
    return sum(comb(n, 2*j)*N**(n-2*j)*W(N, j) for j in range(n//2+1))//N

def word_counts_two_rows(N, nmax):
    """c_n = (1/2) #{words of length n in the letters b^(i), i in Z_2, b in Z_N, equal to 1 in
    Gamma = I_Y x| Y}.  Elements (t, c), t in Z[Z_N] modulo nothing, product (t,c)(t',c') = (t + y^(-c) t', c+c');
    letters c^(0) = (0, c) and c^(1) = (1 - y^(-c), c)."""
    def shift(t, c):                     # multiplication by y^(-c)
        return tuple(t[(k + c) % N] for k in range(N))
    letters = []
    for c in range(N):
        letters.append((tuple([0]*N), c))
        t = [0]*N; t[0] += 1; t[(-c) % N] -= 1
        letters.append((tuple(t), c))
    state = {(tuple([0]*N), 0): 1}; res = []
    for _ in range(nmax):
        new = defaultdict(int)
        for (t, c), m in state.items():
            for (t2, c2) in letters:
                s2 = shift(t2, c)
                new[(tuple(a + b for a, b in zip(t, s2)), (c + c2) % N)] += m
        state = new
        res.append(state.get((tuple([0]*N), 0), 0)//2)
    return res

def lattice_returns(neigh, start, nmax):
    state = {start: 1}; res = []
    for _ in range(nmax):
        new = defaultdict(int)
        for v, m in state.items():
            for w in neigh(v): new[w] += m
        state = new; res.append(state.get(start, 0))
    return res

def kagome(v):
    m, n, s = v
    if s == 0: return [(m, n, 1), (m+1, n, 1), (m, n, 2), (m, n+1, 2)]
    if s == 1: return [(m, n, 0), (m-1, n, 0), (m, n, 2), (m-1, n+1, 2)]
    return [(m, n, 0), (m, n-1, 0), (m, n, 1), (m+1, n-1, 1)]

def honeycomb(v):
    m, n, s = v
    return [(m, n, 1), (m+1, n, 1), (m, n+1, 1)] if s == 0 else [(m, n, 0), (m-1, n, 0), (m, n-1, 0)]

def diamond(v):
    a, b, c, s = v
    return [(a, b, c, 1), (a+1, b, c, 1), (a, b+1, c, 1), (a, b, c+1, 1)] if s == 0 else \
           [(a, b, c, 0), (a-1, b, c, 0), (a, b-1, c, 0), (a, b, c-1, 0)]

