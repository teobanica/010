def part4():
    try:
        from scipy.special import ellipkm1, hyp2f1
        from scipy.integrate import quad
    except Exception:
        out('scipy missing: density checks skipped'); return True
    def p_hyp(r):
        return 2*sqrt(3)*r/(pi*(3 + r*r))*hyp2f1(1/3, 2/3, 1, r*r*(9 - r*r)**2/(3 + r*r)**3)
    def p_ell(r):
        # K(k) with k^2 = 16r/((1+r)^3(3-r)) for r < 1, and k^2 = (1+r)^3(3-r)/(16r) for r > 1;
        # ellipkm1 takes 1 - k^2, which is known in closed form: (1-r)^3(3+r) over the larger of the 2 numbers
        if r < 1:
            hi = (1 + r)**3*(3 - r); return 4*r/(pi*pi*sqrt(hi))*ellipkm1((1 - r)**3*(3 + r)/hi)
        return sqrt(r)/(pi*pi)*ellipkm1((r - 1)**3*(r + 3)/(16*r))
    ok = True
    for name, p in (('hypergeometric', p_hyp), ('elliptic', p_ell)):
        mom = []
        for j in range(6):
            v = quad(lambda r: r**(2*j)*p(r), 0, 1, limit=400)[0] + quad(lambda r: r**(2*j)*p(r), 1, 3, limit=400)[0]
            mom.append(v)
        good = all(abs(mom[j] - W(3, j)) < 1e-6*W(3, j) for j in range(6)); ok &= good
        out('density p_3, %-14s form: moments of order 0, 2, .., 10 = %s  match W_3: %s' % (name, [round(m, 5) for m in mom], good))
    pts = [0.3, 0.9, 1.1, 2.0, 2.9]
    good = all(abs(p_hyp(r) - p_ell(r)) < 1e-9 for r in pts); ok &= good
    out('   the 2 forms agree at r = %s: %s;  p_3(3) = %.8f, sqrt(3)/(2 pi) = %.8f' % (pts, good, p_ell(3 - 1e-12), sqrt(3)/(2*pi)))
    # moments of mu_H = (2/3) delta_0 + (1/6) p_3(|x-3|) dx
    cs = []
    for n in range(1, 7):
        v = sum(quad(lambda x: x**n*p_ell(abs(x - 3))/6, lo, hi, limit=400)[0] for lo, hi in ((0, 2), (2, 3), (3, 4), (4, 6)))
        cs.append(v)
    good = all(abs(cs[n-1] - c_generic_two_rows(3, n)) < 1e-6*cs[n-1] for n in range(1, 7)); ok &= good
    out('   moments of (2/3) delta_0 + (1/6) p_3(|x-3|) dx:', [round(v, 4) for v in cs], 'match c_n:', good)
    return ok

# ------------------------------------------------------------------ 5. p3, Karlsson limits
def moments_exact(al, be, L, nmax):
    """exact c_n for alpha = e(al/L), beta = e(be/L), from mu_H = (2/3) delta_0 + (1/3) law(3 + eps|S|),
    S = 1 + Z_1 + Z_2 on K_Q: c_n = (1/3) sum_j binom(n,2j) 3^(n-2j) E|S|^(2j), where E|S|^(2j) is
    the number of pairs of monomials of S^j whose quotient is a character trivial on K_Q."""
    K = phase_group(al, be, L)
    triv = {(u, v) for u in range(L) for v in range(L) if all((u*z1 + v*z2) % L == 0 for z1, z2 in K)}
    ES = []
    for j in range(nmax//2 + 1):
        mono = [(u, v, comb(j, u)*comb(j - u, v)) for u in range(j + 1) for v in range(j + 1 - u)]
        ES.append(sum(m1*m2 for (u1, v1, m1) in mono for (u2, v2, m2) in mono
                      if ((u1 - u2) % L, (v1 - v2) % L) in triv))
    cs = []
    for n in range(1, nmax + 1):
        tot = sum(comb(n, 2*j)*3**(n - 2*j)*ES[j] for j in range(n//2 + 1))
        assert tot % 3 == 0
        cs.append(tot//3)
    return len(K), cs

def annular(cs):
    """the multiplicities a_k of formula (1.1): c_n = Catalan_n + sum_k binom(2n, n-k) a_k"""
    a = []
    for n in range(1, len(cs) + 1):
        a.append(cs[n-1] - comb(2*n, n)//(n + 1) - sum(comb(2*n, n - k)*a[k-1] for k in range(1, n)))
    return a

def part5():
    ok = True
    out('5. The group p3 and the finite limits of the Karlsson matrices')
    # (a) the relations of p3, in the model of word_counts_two_rows with N = 3
    N = 3
    def mul(g, h):
        (t, c), (t2, c2) = g, h
        s2 = tuple(t2[(k + c) % N] for k in range(N))
        return (tuple(x + y for x, y in zip(t, s2)), (c + c2) % N)
    one = ((0, 0, 0), 0)
    a = ((0, 0, 0), 1); b = ((1, 0, -1), 1)          # 1^(0) and 1^(1) = (1 - y^(-1), 1)
    def power(g, n):
        r = one
        for _ in range(n): r = mul(r, g)
        return r
    ab = mul(a, b)
    rel = power(a, 3) == one and power(b, 3) == one and power(ab, 3) == one
    free = mul(a, b) != mul(b, a) and power(mul(a, power(b, 2)), 3) != one
    out('   a^3 = b^3 = (ab)^3 = 1:', rel, '  ab != ba, and a b^-1 has infinite order (a translation):', free)
    ok &= rel and free
    # (b) the 3 limits
    gen = [c_generic_two_rows(3, n) for n in range(1, 9)]
    data = [('order 24, cube', 2, 4, [1, 4, 18, 88, 456, 2464, 13728], [1, 10, 29, 114, 419],
             lambda n: (3*2**n + 3*4**n + 6**n)//24),
            ('c_4 = 90, K_33', 0, 8, [1, 4, 18, 90], [1, 12, 39, 152, 559],
             lambda n: (4*3**n + 6**n)//18),
            ('order 72, Nauru', 2, 8, gen[:7], None, None)]
    for name, al, be, first, ann, closed in data:
        size, cs = moments_exact(al, be, 12, 8)
        a_k = annular(cs)
        good = cs[:len(first)] == first
        if closed: good &= all(cs[n-1] == closed(n) for n in range(1, 9))
        if ann: good &= a_k[2:7] == ann
        out('   %-16s alpha = e(%d/12), beta = e(%d/12): |K_Q| = %2d, |G_H| = %2d' % (name, al, be, size, 6*size))
        out('      c_n =', cs)
        out('      a_k =', a_k, ' as expected:', good)
        ok &= good
    size, cs = moments_exact(2, 8, 12, 8)
    same = annihilator(phase_group(2, 8, 12), 12) == annihilator(phase_group(0, 2, 12), 12) == ideal(2, 2)
    late = cs[:7] == gen[:7] and cs[7] == 58986 and gen[7] == 58974 and size == 12
    out('   the limit of order 72 has the ideal (2 + 2 zeta) of Example 5.14:', same,
        '  generic moments up to n = 7, then c_8 = 58986 against 58974:', late)
    ok &= same and late
    return ok

